//! Scenario prompts: understanding, creation, and generation probing.

/// 场景一：单图描述（图像理解）。
pub const DESCRIBE: &str = "请仔细观察这张图片，用中文详细描述画面内容：\
包括主体、人物/角色、场景、动作、氛围、风格特点（如漫画分格、对白框等）。\
不要编造画面中不存在的信息。";

/// 场景二：OCR 提取漫画文字。
pub const OCR: &str = "请提取这张漫画图片中的全部文字内容，包括：\
1) 对白框内的台词（按阅读顺序，标明大致位置：上/中/下、左/右）；\
2) 旁白/叙述文字；\
3) 画面中的标题、招牌、标语等文字。\
逐条列出，保持原文，不要改写或润色。";

/// 场景三：多图剧情连贯性理解。
pub const COMPARE: &str = "这里有多张漫画页图片（按 01、02、03 顺序排列）。\
请综合分析：\
1) 三页之间是否构成连贯的剧情？讲述了一个什么故事？\
2) 主要角色是谁？角色在不同页面的状态变化？\
3) 各页的核心事件分别是什么？\
4) 整体画风与叙事节奏有什么特点？";

/// 场景四：创作能力——基于画面内容的二次创作。
pub const CREATE: &str = "请基于这张漫画页的画面内容，完成三项创作任务：\n\
1) 剧情续写：延续本页的剧情走向，续写 200-300 字的后续情节（保持原作画风与人物设定）；\n\
2) 分镜脚本：把本页内容拆解为 4-6 格分镜脚本（每格：景别、画面内容、台词/旁白）；\n\
3) 画风分析：分析本页的画风特征（线条、上色、构图、氛围营造），并给出 3 条创作层面的点评。";

/// 场景四.5：基于理解的图片还原——用 SVG 忠实还原整张图片。
///
/// 核心验证：模型对画面元素（人物/场景/文字/构图）的理解能否转化为
/// 完整、可渲染的矢量重绘。要求完整输出、不省略、不用占位符。
pub const RECREATE: &str = "请基于你对这张图片的理解，用 SVG 代码**完整还原**这张图片：\
1) 画面主体与主要元素（人物、物体、场景背景）按原构图布局；\
2) 关键文字（标题、招牌等）尽量还原；\
3) 使用简洁线条与色块风格（flat style），保证 SVG 可直接渲染；\
4) 必须输出完整可渲染的 <svg>...</svg>，不要省略任何元素，不要使用占位符或注释代替实际绘制。\
**控制输出规模**：viewBox 建议 0 0 800 1200，总元素控制在 80 个以内，避免输出过长被截断，务必以 </svg> 结束。";

/// 还原重试提示词：上一次输出被截断时使用——要求更小规模、必须闭合。
pub const RECREATE_RETRY: &str = "你上一次的 SVG 还原输出被截断了（未以 </svg> 结尾）。\
请重新输出一张**简化但完整闭合**的 SVG 还原图：\
1) viewBox 0 0 800 1200；\
2) 只保留画面最核心的 3-5 个主体元素（人物/物体/标题），使用基础几何图形与色块；\
3) 总元素控制在 40 个以内；\
4) **必须以 </svg> 结尾**，直接输出 SVG 代码，不要任何解释文字。";

/// 文本驱动的还原：只给模型对画面的文字描述（不带原图），让模型
/// 仅凭理解文本重构 SVG——验证「理解 → 视觉重构」的跨模态创作闭环。
pub fn recreate_from_text_prompt() -> String {
    format!(
        "下面是一段对某张图片的详细文字描述（来自视觉模型的理解输出）。\
请仅凭这段文字描述，用 SVG 代码**重构这张图片**：\
1) 根据描述中的主体、场景、构图、文字信息尽量还原画面；\
2) 使用简洁线条与色块风格（flat style），viewBox 0 0 800 1200；\
3) 总元素控制在 80 个以内，避免输出过长被截断；\
4) 必须输出完整可渲染的 <svg>...</svg>，**必须以 </svg> 结尾**，直接输出代码。\n\n\
画面描述如下：\n\"\"\"\n{}\n\"\"\"",
        TEXT_DESCRIPTION_PLACEHOLDER
    )
}

/// 文本驱动还原的重试提示词（简化版、必须闭合）。
pub fn recreate_from_text_retry_prompt() -> String {
    format!(
        "你上一次基于文字描述的 SVG 重构被截断了（未以 </svg> 结尾）。\
请仅凭下面的文字描述，重新输出一张**简化但完整闭合**的 SVG 还原图：\
1) viewBox 0 0 800 1200；\
2) 只保留描述中最核心的 3-5 个主体元素，使用基础几何图形与色块；\
3) 总元素控制在 40 个以内；\
4) **必须以 </svg> 结尾**，直接输出 SVG 代码。\n\n\
画面描述如下：\n\"\"\"\n{}\n\"\"\"",
        TEXT_DESCRIPTION_PLACEHOLDER
    )
}

/// 占位符：在 main 中替换为实际的理解输出文本。
pub const TEXT_DESCRIPTION_PLACEHOLDER: &str = "__TEXT_DESCRIPTION__";

/// 场景五：多模态生成能力探测——四连问。
///
/// 官方文档只承诺图像理解，不承诺图像输出。以下四个探针逐级验证模型
/// 是否具备任何形式的图像/多模态内容生成能力（由易到难）。
pub fn gen_probe_prompts() -> Vec<(&'static str, String)> {
    vec![
        (
            "probe1-svg",
            "请用 SVG 代码重新绘制这张漫画中的主要角色形象（风格简化、线条清晰），\
             直接输出完整可渲染的 <svg> 代码，不要省略。".to_string(),
        ),
        (
            "probe2-ascii",
            "请用 ASCII 字符画（字符画艺术）重新呈现这张图片的核心画面构图，\
             直接输出字符画内容。".to_string(),
        ),
        (
            "probe3-image-url",
            "请基于这张漫画页生成一张新的配图，并以图片 URL 的形式返回（如 https://.../image.png 的完整可访问链接）。\
             如果模型不能直接生成图片文件，请明确说明你的能力边界，不要编造不存在的 URL。".to_string(),
        ),
        (
            "probe4-multimodal-output",
            "请把这张漫画页重绘成一张新的图片（不同构图/不同风格），并将生成的图片以 base64 编码的 data URL \
             （data:image/png;base64,...）直接返回在文本中。如果模型不支持输出图片，请如实回答。".to_string(),
        ),
    ]
}

/// 生成能力探测的收尾确认：让模型自述能力边界。
pub fn gen_probe_summary() -> String {
    "请总结你的多模态能力边界：你是否能生成图片？如果能，支持什么形式（SVG/图片文件/图片 URL）？\
     如果不能，请说明你的输入与输出模态分别是什么。"
        .to_string()
}
